#!/usr/bin/env bash
# =====================================================================
#  CampusRent — демонстрация трёх механизмов репликации.
#
#  Для каждого механизма выводятся три блока:
#     ДО изменения  -> что лежит на узлах сейчас
#     ИЗМЕНЕНИЕ     -> что и где меняем
#     ПОСЛЕ         -> что стало на узлах после репликации
#
#  1) РОК  — репликация с основной копией: справочник меняет только ЦО,
#            филиалы получают копию;
#  2) РБОК — репликация без основной копии: запись заводят в филиале,
#            она появляется и в ЦО, и во втором филиале;
#  3) РКД  — консолидация: данные филиала попадают в сводную копию.
#
#  Скрипт можно запускать повторно: перед каждой вставкой тестовая запись
#  удаляется, а тариф возвращается к базовому значению, поэтому результат
#  при каждом запуске одинаковый.
#
#  Запуск:  bash demo_replication.sh
# =====================================================================
set -uo pipefail

MASTER=mysql-master     # головной офис
SLAVE=mysql-slave       # филиал Санкт-Петербург
SLAVE2=mysql-slave2     # филиал Казань
CONSOL=mysql-consol     # сводный узел
MY="mysql -uroot -ppassword --default-character-set=utf8mb4"

TAR_ID=2011             # тариф модели 201 (проектор Epson EB-X51)
UN_ID=9099              # тестовый вуз
EQ_ID=909900            # тестовый экземпляр техники

q()   { docker exec "$1" $MY --table campusrent -e "$2" 2>/dev/null; }
hdr() { printf '\n\n#####################################################################\n#  %s\n#####################################################################\n' "$*"; }
sub() { printf '\n--- %s\n' "$*"; }
say() { printf '%s\n' "$*"; }

# --- вывод состояния одного узла ------------------------------------
tariff_of() {
  q "$1" "SELECT '$2' AS \`узел\`, TAR_PRICE AS \`цена тарифа $TAR_ID\`
            FROM tariffs WHERE TAR_ID = $TAR_ID;"
}
univ_of() {
  q "$1" "SELECT '$2' AS \`узел\`,
                 IF(COUNT(*) = 0, 'НЕТ', 'ЕСТЬ') AS \`вуз $UN_ID\`,
                 IFNULL(MAX(UN_SHORT), '—')     AS \`краткое название\`
            FROM universities WHERE UN_ID = $UN_ID;"
}
eq_of() {
  q "$1" "SELECT '$2' AS \`узел\`,
                 IF(COUNT(*) = 0, 'НЕТ', 'ЕСТЬ') AS \`экземпляр $EQ_ID\`,
                 IFNULL(MAX(EQ_INV), '—')       AS \`инв. номер\`,
                 IFNULL(MAX(EQ_BR),  '—')       AS \`филиал\`
            FROM equipment_units WHERE EQ_ID = $EQ_ID;"
}

say "Демонстрация репликации CampusRent: РОК, РБОК и консолидация."
say "Для каждого механизма показаны состояния ДО и ПОСЛЕ изменения."

# =====================================================================
hdr "0. Проверка стенда: состояние каналов репликации"
for n in $MASTER $SLAVE $SLAVE2 $CONSOL; do
  st="$(docker exec "$n" $MY -e "SHOW SLAVE STATUS\G" 2>/dev/null)"
  yes_cnt="$(printf '%s' "$st" | grep -c 'Slave_SQL_Running: Yes' || true)"
  err_cnt="$(printf '%s' "$st" | grep -c 'Last_Error: [^ ]' || true)"
  printf '    %-14s каналов в работе: %s, каналов с ошибкой: %s\n' "$n" "${yes_cnt:-0}" "${err_cnt:-0}"
done
say ""
say "    Ожидается: у ЦО, Питера и Казани — по 1 каналу, у сводного узла — 3 канала, ошибок нет."

# =====================================================================
hdr "1. РОК — репликация С ОСНОВНОЙ КОПИЕЙ (справочник ведёт головной офис)"
say "Сценарий: тариф задаёт только центральный офис, филиалы получают копию."

sub "Подготовка: возвращаем тариф к базовому значению (1,2 % от стоимости модели)"
q "$MASTER" "UPDATE tariffs SET TAR_PRICE =
               ROUND((SELECT MOD_COST FROM models WHERE MOD_ID = TAR_MOD) * 0.012, 2)
             WHERE TAR_ID = $TAR_ID;" >/dev/null
sleep 3

sub "ДО изменения — значение тарифа на всех узлах"
tariff_of "$MASTER" "ЦО (головной офис)"
tariff_of "$SLAVE"  "филиал СПб"
tariff_of "$SLAVE2" "филиал Казань"

sub "ИЗМЕНЕНИЕ: увеличиваем тариф на 100 ₽ в головном офисе"
say "    UPDATE tariffs SET TAR_PRICE = TAR_PRICE + 100 WHERE TAR_ID = $TAR_ID;   (на узле ЦО)"
q "$MASTER" "UPDATE tariffs SET TAR_PRICE = TAR_PRICE + 100 WHERE TAR_ID = $TAR_ID;" >/dev/null
sleep 3

sub "ПОСЛЕ изменения — тариф обновился во всех узлах"
tariff_of "$MASTER" "ЦО (головной офис)"
tariff_of "$SLAVE"  "филиал СПб"
tariff_of "$SLAVE2" "филиал Казань"
say ""
say "    ВЫВОД: изменение сделано только в ЦО, но применилось и в обоих филиалах —"
say "    они получают копию справочника. Это и есть репликация с основной копией."

# =====================================================================
hdr "2. РБОК — репликация БЕЗ ОСНОВНОЙ КОПИИ (запись заводит любой филиал)"
say "Сценарий: вуз регистрируют в филиале Санкт-Петербург."

sub "Подготовка: убираем тестовый вуз, если он остался от прошлого запуска"
q "$SLAVE" "DELETE FROM universities WHERE UN_ID = $UN_ID;" >/dev/null
sleep 3

sub "ДО изменения — есть ли вуз $UN_ID в сети"
univ_of "$MASTER" "ЦО (головной офис)"
univ_of "$SLAVE"  "филиал СПб"
univ_of "$SLAVE2" "филиал Казань"

sub "ИЗМЕНЕНИЕ: заводим вуз в филиале Санкт-Петербург"
say "    INSERT INTO universities (UN_ID, UN_NAME, ...) VALUES ($UN_ID, 'Тестовый университет', ...);   (на узле филиала СПб)"
q "$SLAVE" "INSERT INTO universities (UN_ID,UN_NAME,UN_SHORT,UN_INN,UN_ADDRESS,UN_CITY,UN_BR)
            VALUES ($UN_ID,'Тестовый университет','ТЕСТВУЗ','9900000099','ул. Тестовая, 1','Санкт-Петербург','SPB');" >/dev/null
sleep 3

sub "ПОСЛЕ изменения — вуз появился и в ЦО, и во втором филиале"
univ_of "$MASTER" "ЦО (головной офис)"
univ_of "$SLAVE"  "филиал СПб (источник)"
univ_of "$SLAVE2" "филиал Казань"
say ""
say "    ВЫВОД: запись завели в одном филиале, а она разошлась по всей сети."
say "    Основной копии нет: писать может любой узел — это репликация без основной копии."

# =====================================================================
hdr "3. КОНСОЛИДАЦИЯ — данные филиалов собираются в сводной копии"
say "Сценарий: филиал добавляет экземпляр техники; он должен попасть в сводный узел."

sub "Подготовка: убираем тестовый экземпляр, если он остался от прошлого запуска"
q "$SLAVE" "DELETE FROM equipment_units WHERE EQ_ID = $EQ_ID;" >/dev/null
sleep 3

sub "ДО изменения — есть ли экземпляр $EQ_ID в филиале и в сводной копии"
eq_of "$SLAVE"  "филиал СПб"
eq_of "$CONSOL" "сводный узел"

sub "ИЗМЕНЕНИЕ: добавляем экземпляр техники в филиале Санкт-Петербург"
say "    INSERT INTO equipment_units (EQ_ID, EQ_INV, ...) VALUES ($EQ_ID, 'SPB-$EQ_ID', ...);   (на узле филиала СПб)"
q "$SLAVE" "INSERT INTO equipment_units (EQ_ID,EQ_INV,EQ_MOD,EQ_BR,EQ_STATUS,EQ_COND,EQ_ACQUIRE)
            VALUES ($EQ_ID,'SPB-$EQ_ID',201,'SPB','свободна',2,'2026-09-01');" >/dev/null
sleep 3

sub "ПОСЛЕ изменения — экземпляр есть и в филиале, и в сводной копии"
eq_of "$SLAVE"  "филиал СПб (источник)"
eq_of "$CONSOL" "сводный узел"
say ""
say "    ВЫВОД: данные, созданные в филиале, автоматически попали в сводную копию."
say "    Из неё руководство строит отчёты по всей сети — это консолидация."

# =====================================================================
hdr "4. Итог"
say "    РОК:   изменили в ЦО            -> обновилось в обоих филиалах (проверка 1)."
say "    РБОК:  завели в одном филиале   -> появилось в ЦО и втором филиале (проверка 2)."
say "    РКД:   завели в филиале         -> попало в сводную копию (проверка 3)."
say ""
say "    Полный протокол проверки: results/replication_log.md"
say "    Распределённая транзакция (бронирование в другом филиале): bash distributed_booking.sh"
