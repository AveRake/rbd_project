def set_font(run, name=BODY_FONT, size=BODY_SIZE, bold=False, italic=False, color=None):
    run.font.name = name
    run.font.size = size
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rFonts.set(qn(attr), name)


def para(doc, text="", size=BODY_SIZE, bold=False, italic=False, align=None,
         indent=True, space_after=6, space_before=0, line=1.5, style=None,
         font=BODY_FONT, color=None):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.25) if indent else Cm(0)
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = line
    if text:
        run = p.add_run(text)
        set_font(run, font, size, bold, italic, color)
    return p


def heading(doc, text, level=1, page_break=False):
    if page_break:
        doc.add_page_break()
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(0 if page_break else (18 if level == 1 else 12))
    pf.space_after = Pt(12 if level == 1 else 8)
    pf.line_spacing = 1.5
    pf.keep_with_next = True
    run = p.add_run(text)
    set_font(run, BODY_FONT, Pt(16 if level == 1 else 14), bold=True,
             color="000000")
    # помечаем уровень для навигации
    p.style = doc.styles["Heading %d" % level]
    for r in p.runs:
        set_font(r, BODY_FONT, Pt(16 if level == 1 else 14), bold=True, color="000000")
    return p


def bullets(doc, items, size=BODY_SIZE):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.line_spacing = 1.4
        p.paragraph_format.left_indent = Cm(1.0)
        run = p.add_run(it)
        set_font(run, BODY_FONT, size)


def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def table_borders(table, color="D9D9D9", size=6):
    tbl = table._tbl
    tblPr = tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement("w:%s" % edge)
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), str(size))
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), color)
        borders.append(el)
    tblPr.append(borders)


def add_table(doc, headers, rows, widths=None, font_size=Pt(11), header_fill="DCE6F1",
              align_center=True, caption=None):
    if caption:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.keep_with_next = True
        run = p.add_run(caption)
        set_font(run, BODY_FONT, Pt(12), italic=True)
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    table_borders(table)
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(str(h))
        set_font(run, BODY_FONT, font_size, bold=True)
        shade(hdr[i], header_fill)
    for r_i, row in enumerate(rows):
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.line_spacing = 1.0
            p.alignment = (WD_ALIGN_PARAGRAPH.CENTER if (align_center and i > 0 and len(str(val)) < 18)
                           else WD_ALIGN_PARAGRAPH.LEFT)
            run = p.add_run(str(val))
            set_font(run, BODY_FONT, font_size)
        if r_i % 2 == 1:
            for c in cells:
                shade(c, "F2F6FB")
    if widths:
        for row in table.rows:
            for i, wd in enumerate(widths):
                row.cells[i].width = Cm(wd)
    doc.add_paragraph().paragraph_format.space_after = Pt(6)
    return table


def add_figure(doc, filename, caption, width_cm=16.0, folder=DIAG):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.first_line_indent = Cm(0)
    p.add_run().add_picture(os.path.join(folder, filename), width=Cm(width_cm))
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cp.paragraph_format.space_after = Pt(12)
    cp.paragraph_format.first_line_indent = Cm(0)
    run = cp.add_run(caption)
    set_font(run, BODY_FONT, Pt(12), italic=True)


def add_code(doc, lines, size=Pt(9.5)):
    for ln in lines:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.space_after = Pt(0)
        pf.space_before = Pt(0)
        pf.line_spacing = 1.0
        pf.first_line_indent = Cm(0)
        pf.left_indent = Cm(0.6)
        run = p.add_run(ln if ln else " ")
        set_font(run, MONO_FONT, size, color="1F3864")
    doc.add_paragraph().paragraph_format.space_after = Pt(8)


def add_page_numbers(section):
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    set_font(run, BODY_FONT, Pt(12))
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = "1"
    r.append(t)
    fld.append(r)
    p._p.append(fld)


